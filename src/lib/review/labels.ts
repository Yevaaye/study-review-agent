/**
 * 复习相关的界面文案。
 *
 * 为什么单独抽出来：同一句状态原来在三个地方各写一遍（复习页书籍行、统计页
 * 书籍行、首页主按钮），改一处必然会漏另外两处，于是出现「书库显示已复习、
 * 首页却写着没有到期」这种自相矛盾的说法。
 *
 * 另一个原因是措辞本身：「无到期」描述的是 DSRS 排期的内部状态，用户读到的
 * 却是「这书是不是有问题 / 我是不是没学」——真实的用户反馈是「我明明今天刷完了，
 * 为什么它说无到期」。所以对外统一说人话：**已复习**。
 */
export const REVIEWED_LABEL = "已复习";

/**
 * 一本书「今天还有没有活」的状态标签。
 * 还有待复习的卡 → null（调用方自己展示数量 + 按钮）；没有了 → 「已复习」。
 */
export function reviewedLabel(due: number): string | null {
  return due > 0 ? null : REVIEWED_LABEL;
}
